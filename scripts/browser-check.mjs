import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { ROOT, defaults } from '../src/catalog.mjs';
import { nativeLayer } from '../src/native-layer.mjs';
import { createMediaDeck } from '../src/media-player.mjs';
import { startServer } from '../src/server.mjs';

const moduleRoot = process.env.ARK_TEST_MODULES;
if (!moduleRoot) throw new Error('Set ARK_TEST_MODULES to the available Playwright node_modules directory');
const require = createRequire(path.join(moduleRoot,'package.json'));
const { chromium } = require('playwright');
const testDir=await fs.mkdtemp(path.join(ROOT,'.local','browser-check-'));
const lab=await startServer({stateDir:testDir});
const session={url:lab.url};
const output = path.join(ROOT,'test-results');await fs.mkdir(output,{recursive:true});
const browser = await chromium.launch({headless:true,executablePath:process.env.ARK_TEST_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const errors=[], results=[];
try {
  const context=await browser.newContext({viewport:{width:1480,height:1040},deviceScaleFactor:1});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto(session.url);await page.locator('.scene-choice').last().waitFor({state:'attached'});
  await page.waitForFunction(()=>document.querySelector('#scene-video').readyState>=2,{},{timeout:30000});
  await page.locator('#test-input').fill('明日方舟 · 中文输入与阅读检查');
  assert.equal(await page.locator('#test-input').inputValue(),'明日方舟 · 中文输入与阅读检查');
  await page.screenshot({path:path.join(output,'lab-desktop.png'),fullPage:true});
  results.push({check:'desktop preview and Chinese text entry',passed:true});
  await page.locator('#theme-open').click();
  await page.locator('#wallpaper-library .tune').click();
  assert.equal(await page.locator('#source-spec').count(),0);
  for(const id of ['eyja','shu-1','shu-2','yaoyue']) {
    await page.locator(`.scene-choice[data-id="${id}"]`).click();
    await page.waitForFunction(expected=>{const v=document.querySelector('#scene-video');return v.readyState>=2&&v.currentSrc.includes(`/media/${expected}/`);},id,{timeout:30000});
    const metadata=await page.locator('#scene-video').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,muted:v.muted,duration:v.duration,error:v.error?.code??null}));
    assert.equal(metadata.error,null);assert.equal(metadata.muted,true);
    results.push({check:`source playback: ${id}`,passed:true,...metadata});
  }
  await page.locator('#blur').fill('7');await page.locator('#blur').dispatchEvent('input');
  await page.waitForFunction(()=>document.querySelector('#save-state').textContent.includes('已保存'));
  await page.reload();await page.locator('.scene-choice').last().waitFor({state:'attached'});await page.locator('#theme-open').click();await page.locator('#wallpaper-library .tune').click();assert.equal(await page.locator('#blur').inputValue(),'7');
  results.push({check:'settings survive reload',passed:true});
  await page.locator('#reset').click();
  await page.locator('[data-mode="focus"]').click();assert.equal(await page.locator('#scene-video').evaluate(v=>v.paused),true);
  await page.locator('[data-mode="balanced"]').click();
  await page.locator('#theme-close').click();
  await page.locator('[data-tab="startup"]').click();assert.equal(await page.locator('#scene-video').evaluate(v=>v.paused),true);
  await page.locator('#boot-play').click();await page.waitForTimeout(350);await page.screenshot({path:path.join(output,'wake-preview.png')});
  await page.keyboard.press('Escape');assert.equal(await page.locator('#boot-dialog').evaluate(d=>d.open),false);
  results.push({check:'focus/tab pause, vector wake preview and Escape',passed:true});
  await page.locator('[data-tab="integration"]').click();await page.locator('#probe').click();
  await page.waitForFunction(()=>!document.querySelector('#probe').disabled,{},{timeout:30000});
  const hostAccessible=!(await page.locator('#apply-poster').isDisabled());
  const host={version:await page.locator('#host-version').textContent(),debug:await page.locator('#host-debug').textContent()};
  await page.screenshot({path:path.join(output,'host-check.png'),fullPage:true});
  results.push({check:'actual host probe recognizes verified desktop access',passed:hostAccessible,skipped:!hostAccessible,...host,reason:hostAccessible?null:await page.locator('#host-reason').textContent()});
  await page.locator('[data-tab="scenes"]').click();await page.setViewportSize({width:390,height:844});
  const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,nodes:[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1).map(e=>({tag:e.tagName,cls:e.className,right:e.getBoundingClientRect().right})).slice(0,10)}));
  if(overflow.scroll>overflow.width+1)console.log(JSON.stringify(overflow));
  assert.equal(overflow.scroll<=overflow.width+1,true);
  await page.screenshot({path:path.join(output,'lab-narrow.png'),fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>matchMedia('(prefers-reduced-motion: reduce)').matches&&document.querySelector('#scene-video').paused,{},{timeout:3000});
  results.push({check:'narrow layout and reduced motion',passed:true});
  // Isolated structural fixture. This is NOT an integration test of the real app.
  const fixture=await context.newPage();await fixture.goto(new URL('/',session.url).href);
  await fixture.setContent('<div id="root"><div class="app-shell"><aside class="app-shell-left-panel"><nav data-app-navigation-rail><div data-appearance="plain"></div></nav></aside><main data-app-shell-main-surface><div data-composer-body><textarea></textarea></div><button id="fixture-button">input works</button></main></div></div>');
  const rejected=await fixture.evaluate(`(${nativeLayer.toString()})('inspect')`);assert.equal(rejected.eligible,false);
  const poster=`data:image/jpeg;base64,${(await fs.readFile(path.join(ROOT,'.local','posters','yaoyue.jpg'))).toString('base64')}`;
  const settings={...defaults,strength:.6,blur:0,panel:.9,shade:.3,focusX:50,focusY:50,motion:false,quality:'still',mode:'balanced'};
  const run=(command,payload={})=>fixture.evaluate(`(async()=>{const location={protocol:'app:'};return (${nativeLayer.toString()})(${JSON.stringify(command)},${JSON.stringify(payload)},${createMediaDeck.toString()});})()`);
  assert.equal((await run('apply',{poster,settings})).applied,true);
  assert.equal(await fixture.locator('#ark-theme-lab-layer').count(),1);
  await fixture.locator('textarea').fill('fixture text');
  assert.equal((await run('apply',{poster,settings})).applied,true);assert.equal(await fixture.locator('#ark-theme-lab-layer').count(),1);
  assert.equal((await run('remove')).restored,true);assert.equal(await fixture.locator('textarea').inputValue(),'fixture text');
  assert.equal(await fixture.locator('html').getAttribute('data-ark-theme-lab'),null);
  await run('apply',{poster,settings});await fixture.keyboard.press('Control+Shift+Backspace');assert.equal(await fixture.locator('#ark-theme-lab-layer').count(),0);
  await run('apply',{poster,settings});await fixture.evaluate(()=>window.__ARK_THEME_LAB_V1__.heartbeat=Date.now()-30000);
  await fixture.waitForFunction(()=>!window.__ARK_THEME_LAB_V1__,{},{timeout:5000});
  results.push({check:'fixture only: origin rejection, idempotent mount, input, cleanup, emergency key, watchdog',passed:true});
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(output,'browser-results.json'),JSON.stringify({testedAt:new Date().toISOString(),nativeHostApplied:false,results,errors},null,2));
  console.log(JSON.stringify({passed:results.filter(r=>r.passed).length,skipped:results.filter(r=>r.skipped).length,errors,results},null,2));
} finally {await browser.close();await lab.close();if(path.dirname(testDir)!==path.join(ROOT,'.local')||!path.basename(testDir).startsWith('browser-check-'))throw new Error('Unexpected test path');await fs.rm(testDir,{recursive:true,force:true});}
