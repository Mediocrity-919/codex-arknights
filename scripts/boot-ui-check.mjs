import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
const root=path.resolve(import.meta.dirname,'..');
const require=createRequire(process.env.ARK_TEST_MODULES?path.join(process.env.ARK_TEST_MODULES,'package.json'):import.meta.url);
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.ARK_CHROME??'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const context=await browser.newContext({viewport:{width:1600,height:900}}),page=await context.newPage(),errors=[],remote=[];
page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
await page.addInitScript(()=>{window.__messages=[];window.chrome.webview={postMessage:data=>window.__messages.push(data),addEventListener:()=>{}};});
const load=async()=>{await page.goto(pathToFileURL(path.join(root,'launcher/ui/index.html')).href);await page.evaluate(()=>window.arkBoot.start({launchId:'test'}));};
try{
  await load();await page.waitForTimeout(2100);await page.screenshot({path:path.join(root,'test-results/boot-production-title.png')});
  const skipBox=await page.locator('#skip').boundingBox(),versionBox=await page.locator('.idv').boundingBox();
  assert.ok(skipBox.x>=versionBox.x+versionBox.width||skipBox.y+skipBox.height<=versionBox.y,'skip must not cover footer version');
  await page.evaluate(()=>window.arkBoot.status({launchId:'stale',phase:3,ready:true}));
  assert.equal(await page.evaluate(()=>window.arkBoot.diagnostics().phase),0);
  await page.evaluate(()=>window.arkBoot.status({launchId:'test',phase:2,message:'正在准备壁纸首帧'}));
  await page.waitForTimeout(2600);await page.screenshot({path:path.join(root,'test-results/boot-production-sphere.png')});
  assert.equal(await page.evaluate(()=>window.arkBoot.diagnostics().completed),false,'real readiness must gate handoff');
  await page.evaluate(()=>window.arkBoot.status({launchId:'test',phase:3,ready:true}));
  await page.waitForTimeout(1000);await page.screenshot({path:path.join(root,'test-results/boot-production-wave.png')});
  await page.waitForFunction(()=>window.arkBoot.diagnostics().completed);
  const finished=await page.evaluate(()=>window.arkBoot.diagnostics());await page.waitForTimeout(700);
  assert.deepEqual(await page.evaluate(()=>window.arkBoot.diagnostics()),finished,'canvas scheduling must stop');
  assert.equal(await page.evaluate(()=>document.getAnimations().filter(a=>a.playState==='running').length),0);
  assert.equal(await page.evaluate(()=>window.__messages.filter(m=>m.type==='handoff-ready').length),1);
  await load();await page.keyboard.press('Escape');await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>window.__messages.filter(m=>m.type==='skip').length),1);
  await page.setViewportSize({width:2560,height:1080});
  assert.equal((await page.locator('#stage').boundingBox()).width,2560);
  await page.emulateMedia({reducedMotion:'reduce'});await load();
  await page.evaluate(()=>window.arkBoot.status({launchId:'test',phase:3,ready:true}));
  await page.waitForFunction(()=>window.arkBoot.diagnostics().completed);
  assert.equal(await page.evaluate(()=>window.arkBoot.diagnostics().draws),0);
  assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
  const report={passed:true,checks:['real readiness','stale launch ignored','single handoff','RAF and CSS stopped','Escape once','ultrawide','reduced motion','offline'],finished,errors,remote};
  await fs.writeFile(path.join(root,'test-results/boot-ui-check.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{await browser.close();}
